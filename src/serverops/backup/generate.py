"""Generate staged backup configs for review before install."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from serverops.backup.models import BackupConfigModel
from serverops.paths import REPO_ROOT, data_path
from serverops.utils.filesystem import ensure_parent


def default_output_dir() -> Path:
    return data_path("backups", "generated")


def generate_configs(
    config: BackupConfigModel,
    *,
    output_dir: Path | None = None,
) -> dict[str, Path]:
    """Write borgmatic, credentials example, systemd units, and backup.yaml."""
    target = output_dir or default_output_dir()
    target.mkdir(parents=True, exist_ok=True)

    written: dict[str, Path] = {}
    written["backup_yaml"] = _write_text(target / "backup.yaml", _backup_yaml(config))
    written["borgmatic"] = _write_text(target / "borgmatic.yaml", _borgmatic_yaml(config))
    written["credentials_example"] = _write_text(
        target / "credentials.env.example", _credentials_example(config)
    )
    written["service"] = _write_text(target / "server-backup.service", _backup_service(config))
    written["timer"] = _write_text(target / "server-backup.timer", _backup_timer(config))
    written["check_service"] = _write_text(
        target / "server-backup-check.service", _check_service(config)
    )
    written["check_timer"] = _write_text(target / "server-backup-check.timer", _check_timer())
    written["borgmatic_dropin"] = _write_text(
        target / "borgmatic.service.d" / "credentials.conf",
        _borgmatic_credentials_dropin(config),
    )
    return written


def _write_text(path: Path, content: str) -> Path:
    ensure_parent(path)
    path.write_text(content if content.endswith("\n") else content + "\n", encoding="utf-8")
    return path


def _backup_yaml(config: BackupConfigModel) -> str:
    payload: dict[str, Any] = {
        "version": config.version,
        "server": {
            "name": config.server_name,
            "staging_directory": config.staging_directory,
            "restore_directory": config.restore_directory,
            "lock_file": config.lock_file,
        },
        "deploy": config.deploy.model_dump(),
        "repository": config.repository.model_dump(),
        "sources": {
            "mandatory": config.mandatory_sources,
            "host_configuration": config.host_configuration,
            "additional": config.additional_sources,
        },
        "exclusions": config.exclusions,
        "retention": config.retention.model_dump(),
        "scheduling": config.scheduling.model_dump(),
    }
    return yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)


def _borgmatic_yaml(config: BackupConfigModel) -> str:
    sources = [
        *config.mandatory_sources,
        *config.host_configuration,
        *config.additional_sources,
        # Native dumps land here before borgmatic create; must be archived.
        config.staging_directory,
    ]
    # De-dupe while preserving order
    seen: set[str] = set()
    unique_sources: list[str] = []
    for path in sources:
        if path not in seen:
            seen.add(path)
            unique_sources.append(path)
    payload = {
        "source_directories": unique_sources,
        "repositories": [
            {
                "path": config.repository.url,
                "label": "storagebox",
            }
        ],
        "exclude_patterns": config.exclusions,
        "keep_within": config.retention.keep_within,
        "keep_daily": config.retention.keep_daily,
        "keep_weekly": config.retention.keep_weekly,
        "keep_monthly": config.retention.keep_monthly,
        "keep_yearly": config.retention.keep_yearly,
        "encryption_passcommand": (
            f"cat {config.repository.passphrase_file}"
            if config.repository.passphrase_file
            else f"printenv {config.repository.passphrase_environment_variable}"
        ),
        "ssh_command": f"ssh -i {config.repository.ssh_key} -p 23 -o BatchMode=yes",
        "archive_name_format": f"{config.server_name}-full-{{now}}",
    }
    header = (
        "# Generated by serverops backup generate-config.\n"
        "# Review before copying to /etc/borgmatic/config.yaml.\n"
        "# Passphrase comes from Vault KV via Agent-rendered "
        f"{config.repository.passphrase_file} — do not paste secrets here.\n"
    )
    return header + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)


def _credentials_example(config: BackupConfigModel) -> str:
    return (
        "# Copy to /etc/server-backup/credentials.env with mode 0600.\n"
        "# Never commit real values.\n"
        f"# Optional fallback if Vault Agent is not rendering "
        f"{config.repository.passphrase_file} yet.\n"
        f"{config.repository.passphrase_environment_variable}=\n"
        "# BACKUP_START_URL=\n"
        "# BACKUP_SUCCESS_URL=\n"
        "# BACKUP_FAILURE_URL=\n"
    )


def _borgmatic_credentials_dropin(config: BackupConfigModel) -> str:
    env_var = config.repository.passphrase_environment_variable
    return f"""[Service]
# Distro borgmatic.service does not load ServerOps credentials.
# encryption_passcommand uses printenv {env_var} until
# /etc/server-backup/borg-passphrase is rendered from Vault KV.
EnvironmentFile=-{config.deploy.credentials_file}
"""


def _unit_environment(config: BackupConfigModel) -> str:
    return (
        f"EnvironmentFile=-{config.deploy.credentials_file}\n"
        f"WorkingDirectory={config.deploy.install_root}\n"
        "UMask=0077\n"
    )


def _backup_service(config: BackupConfigModel) -> str:
    install_root = config.deploy.install_root
    return f"""[Unit]
Description=ServerOps full host backup
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=oneshot
User=root
{_unit_environment(config)}ExecStart={install_root}/.venv/bin/serverops backup run --apply
Nice=10
IOSchedulingClass=best-effort
IOSchedulingPriority=7

[Install]
WantedBy=multi-user.target
"""


def _backup_timer(config: BackupConfigModel) -> str:
    persistent = "true" if config.scheduling.persistent else "false"
    return f"""[Unit]
Description=Nightly ServerOps backup timer

[Timer]
OnCalendar={config.scheduling.nightly_calendar}
Persistent={persistent}
RandomizedDelaySec={config.scheduling.randomized_delay_seconds}
Unit=server-backup.service

[Install]
WantedBy=timers.target
"""


def _check_service(config: BackupConfigModel) -> str:
    install_root = config.deploy.install_root
    return f"""[Unit]
Description=ServerOps Borg repository check
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
User=root
{_unit_environment(config)}ExecStart={install_root}/.venv/bin/serverops backup check --apply
Nice=10

[Install]
WantedBy=multi-user.target
"""


def _check_timer() -> str:
    return """[Unit]
Description=Weekly ServerOps backup repository check

[Timer]
OnCalendar=Sun *-*-* 04:30:00
Persistent=true
RandomizedDelaySec=1800
Unit=server-backup-check.service

[Install]
WantedBy=timers.target
"""


def template_dir() -> Path:
    return REPO_ROOT / "deploy" / "systemd"
